def _short_chunk_content(max_tokens: int = 49) -> st.SearchStrategy[str]:
    """Chunk content with fewer than max_tokens whitespace-separated words."""
    return st.lists(
        st.text(
            alphabet=st.characters(whitelist_categories=("L", "N")),
            min_size=1,
            max_size=20,
        ).filter(lambda s: s.strip()),
        min_size=0,
        max_size=max_tokens - 1,
    ).map(lambda words: " ".join(words))


def _long_chunk_content(min_tokens: int = 50) -> st.SearchStrategy[str]:
    """Chunk content with at least min_tokens whitespace-separated words."""
    return st.lists(
        st.text(
            alphabet=st.characters(whitelist_categories=("L", "N")),
            min_size=1,
            max_size=20,
        ).filter(lambda s: s.strip()),
        min_size=min_tokens,
        max_size=min_tokens + 100,
    ).map(lambda words: " ".join(words))


def _min_chunk_tokens_threshold() -> st.SearchStrategy[int]:
    """Configurable minimum chunk token threshold."""
    return st.integers(min_value=1, max_value=200)


