# All known semantic types from TEMPLATES_BY_SEMANTIC_TYPE,
# plus arbitrary strings to exercise the default fallback path.
_KNOWN_SEMANTIC_TYPES = list(TEMPLATES_BY_SEMANTIC_TYPE.keys())

# Maximum template index across all template lists (used to cycle templates).
_MAX_TEMPLATE_INDEX = max(
    len(ts) for ts in (
        list(TEMPLATES_BY_SEMANTIC_TYPE.values())
        + [DEFAULT_QUESTION_TEMPLATES]
    )
)


def _concept_name() -> st.SearchStrategy[str]:
    """Non-empty concept name with at least one non-whitespace char."""
    return st.text(
        alphabet=st.characters(
            whitelist_categories=("L", "N", "Zs", "Pd"),
            whitelist_characters="-' ",
        ),
        min_size=1,
        max_size=200,
    ).filter(lambda s: s.strip())


def _semantic_type() -> st.SearchStrategy[str]:
    """Known semantic type or arbitrary string (fallback path)."""
    return st.one_of(
        st.sampled_from(_KNOWN_SEMANTIC_TYPES),
        st.text(min_size=1, max_size=100).filter(
            lambda s: s.strip()
        ),
    )


def _synonyms() -> st.SearchStrategy[list[str] | None]:
    """Optional list of synonym strings."""
    return st.one_of(
        st.none(),
        st.lists(
            st.text(min_size=1, max_size=100).filter(
                lambda s: s.strip()
            ),
            max_size=10,
        ),
    )


def _template_index() -> st.SearchStrategy[int]:
    """Non-negative template index (may exceed list length)."""
    return st.integers(
        min_value=0, max_value=_MAX_TEMPLATE_INDEX * 3
    )


