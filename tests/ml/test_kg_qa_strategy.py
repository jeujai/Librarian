def _source_document() -> st.SearchStrategy[str]:
    """Non-empty source document title."""
    return st.text(
        alphabet=st.characters(
            whitelist_categories=("L", "N", "Zs"),
            whitelist_characters="'-.,:()",
        ),
        min_size=1,
        max_size=200,
    ).filter(lambda s: s.strip())


def _chunk_id() -> st.SearchStrategy[str]:
    """Non-empty chunk identifier."""
    return st.from_regex(r"[a-zA-Z0-9][a-zA-Z0-9_-]{0,49}", fullmatch=True)


def _chunk_content() -> st.SearchStrategy[str]:
    """Non-empty chunk content with at least a few words."""
    # Build content from word lists to avoid heavy filtering
    return st.lists(
        st.text(
            alphabet=st.characters(whitelist_categories=("L", "N")),
            min_size=1,
            max_size=20,
        ).filter(lambda s: s.strip()),
        min_size=3,
        max_size=50,
    ).map(lambda words: " ".join(words))


